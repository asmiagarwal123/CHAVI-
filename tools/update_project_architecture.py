"""Generate the authoritative, exhaustive CHAVI repository architecture map."""
from __future__ import annotations

import os
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "PROJECT_ARCHITECTURE.md"
EXCLUDED_DIRS = {".git", ".venv", ".uv-cache", "__pycache__", ".pytest_cache"}
EXCLUDED_FILES = {"PROJECT_ARCHITECTURE.md"}


def included_children(directory: Path) -> list[Path]:
    children = []
    for child in directory.iterdir():
        if child.is_dir() and child.name in EXCLUDED_DIRS:
            continue
        if child.is_file() and child.name in EXCLUDED_FILES:
            continue
        children.append(child)
    return sorted(children, key=lambda p: (not p.is_dir(), p.name.casefold(), p.name))


def render_tree(directory: Path, prefix: str = "") -> list[str]:
    lines: list[str] = []
    children = included_children(directory)
    for index, child in enumerate(children):
        last = index == len(children) - 1
        branch = "└── " if last else "├── "
        suffix = "/" if child.is_dir() else ""
        lines.append(f"{prefix}{branch}{child.name}{suffix}")
        if child.is_dir():
            extension = "    " if last else "│   "
            lines.extend(render_tree(child, prefix + extension))
    return lines


def collect_counts() -> tuple[int, int, Counter[str]]:
    directories = 0
    files = 0
    extensions: Counter[str] = Counter()
    for current, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDED_DIRS)
        directories += len(dirnames)
        for filename in filenames:
            if filename in EXCLUDED_FILES:
                continue
            files += 1
            suffix = Path(filename).suffix.lower() or "[no extension]"
            extensions[suffix] += 1
    return directories, files, extensions


def top_level_summary() -> list[str]:
    rows = []
    for child in included_children(ROOT):
        if child.is_dir():
            dir_count = file_count = 0
            for _, dirnames, filenames in os.walk(child):
                dirnames[:] = [d for d in dirnames if d not in EXCLUDED_DIRS]
                dir_count += len(dirnames)
                file_count += sum(name not in EXCLUDED_FILES for name in filenames)
            rows.append(f"| `{child.name}/` | Directory | {dir_count} | {file_count} |")
        else:
            rows.append(f"| `{child.name}` | File | — | 1 |")
    return rows


def main() -> int:
    directories, files, extensions = collect_counts()
    tree = [f"{ROOT.name}/", *render_tree(ROOT)]
    extension_rows = [f"| `{ext}` | {count} |" for ext, count in sorted(extensions.items(), key=lambda item: (-item[1], item[0]))]
    content = "\n".join([
        "# CHAVI project architecture",
        "",
        "> This file is generated by `tools/update_project_architecture.py`. Do not edit the generated inventory manually.",
        "",
        "## Inventory policy",
        "",
        "This document exhaustively lists repository content except environment and cache internals: "
        + ", ".join(f"`{name}`" for name in sorted(EXCLUDED_DIRS))
        + ". The architecture file itself is omitted from its own tree to keep generation stable.",
        "",
        f"Inventory totals: **{directories} directories** and **{files} files**.",
        "",
        "## Root structure",
        "",
        "| Root entry | Type | Nested directories | Nested files |",
        "|---|---:|---:|---:|",
        *top_level_summary(),
        "",
        "## File-type inventory",
        "",
        "| Extension | Files |",
        "|---|---:|",
        *extension_rows,
        "",
        "## Complete repository tree",
        "",
        "```text",
        *tree,
        "```",
        "",
        "## Maintenance rule",
        "",
        "After any filesystem addition, deletion, rename, or move, run:",
        "",
        "```powershell",
        ".\\.venv\\Scripts\\python.exe tools\\update_project_architecture.py",
        "```",
        "",
    ])
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Updated {OUTPUT.name}: {directories} directories, {files} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
